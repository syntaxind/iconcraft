export async function exportHighResPngZip(
  icons: GeneratedIconItem[],
  shape: IconShape = 'squircle',
  onProgress?: (percent: number, msg: string) => void,
  size = 1024,
): Promise<Blob> {
  const valid = icons.filter(isExportable);
  if (valid.length === 0) throw new Error('Tidak ada ikon yang siap diekspor. / No icons ready to export.');
  size = clampSize(size);
  const zip = new JSZip();
  const names = buildDrawableNames(valid.map((i) => i.appName));

  for (let i = 0; i < valid.length; i++) {
    zip.file(`${names[i]}.png`, await renderPng(valid[i], size, shape));
    onProgress?.(Math.round(((i + 1) / valid.length) * 97), valid[i].appName);
  }
  return zip.generateAsync({ type: 'blob' });
}

export async function exportSvgZip(icons: GeneratedIconItem[]): Promise<Blob> {
  const valid = icons.filter((i) => i.status === 'ready' && i.svg);
  if (valid.length === 0) throw new Error('Tidak ada ikon vektor. / No vector icons to export.');
  const zip = new JSZip();
  const names = buildDrawableNames(valid.map((i) => i.appName));
  valid.forEach((icon, i) => zip.file(`${names[i]}.svg`, sanitizeSvg(icon.svg!)));
  return zip.generateAsync({ type: 'blob' });
}
