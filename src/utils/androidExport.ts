import JSZip from 'jszip';
import type { GeneratedIconItem, IconShape, StyleDNA } from '../types/iconTheme';
import { getComponentCandidates } from './presets';
import { rasterizeSvgToBlob, rasterizeDataUrlToBlob } from './canvasRasterizer';
import { sanitizeSvg, escapeXml } from '../shared/svg';
import { slugify } from './download';

export const DENSITIES = [
  { folder: 'res/drawable-xxxhdpi', size: 192 },
  { folder: 'res/drawable-xxhdpi', size: 144 },
  { folder: 'res/drawable-xhdpi', size: 96 },
  { folder: 'res/drawable-hdpi', size: 72 },
  { folder: 'res/drawable-mdpi', size: 48 },
];

export const MIN_SIZE = 16;
export const MAX_SIZE = 2048;
export const clampSize = (n: number) => Math.min(MAX_SIZE, Math.max(MIN_SIZE, Math.round(Number(n) || 512)));

const isExportable = (i: GeneratedIconItem) => i.status === 'ready' && Boolean(i.svg || i.imageUrl);

/**
 * Android resource names must be lowercase [a-z0-9_] and start with a letter.
 * Returns one unique name per icon, in order.
 */
export function buildDrawableNames(appNames: string[]): string[] {
  const used = new Set<string>();
  return appNames.map((name) => {
    let base = slugify(name, 'icon');
    if (!/^[a-z]/.test(base)) base = `app_${base}`;
    let candidate = base;
    for (let n = 2; used.has(candidate); n++) candidate = `${base}_${n}`;
    used.add(candidate);
    return candidate;
  });
}

export interface AppFilterEntry {
  drawable: string;
  appName: string;
  component: string; // "pkg/activity"
}

/** Builds the appfilter.xml understood by Nova, Lawnchair, Smart Launcher, etc. */
export function buildAppFilterXml(entries: AppFilterEntry[], styleName: string): string {
  const lines = entries.map(
    (e) => `  <!-- ${escapeXml(e.appName).replace(/--/g, '-')} -->\n  <item component="ComponentInfo{${escapeXml(e.component)}}" drawable="${e.drawable}" />`,
  );
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${escapeXml(styleName).replace(/--/g, '-')} icon pack - generated by IconCraft AI -->\n<resources>\n  <scale factor="1.0" />\n${lines.join('\n')}\n</resources>\n`;
}

/** Builds drawable.xml (icon list used by launcher icon pickers). */
export function buildDrawableXml(drawables: string[]): string {
  const items = drawables.map((d) => `  <item drawable="${d}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n  <version>1</version>\n  <category title="All" />\n${items}\n</resources>\n`;
}

async function renderPng(icon: GeneratedIconItem, size: number, shape: IconShape): Promise<Blob> {
  if (icon.svg) return rasterizeSvgToBlob(sanitizeSvg(icon.svg), size, shape);
  if (icon.imageUrl) return rasterizeDataUrlToBlob(icon.imageUrl, size, shape);
  throw new Error('No artwork');
}

export async function exportAndroidIconPackZip(
  icons: GeneratedIconItem[],
  styleDNA: StyleDNA,
  shape: IconShape = 'squircle',
  onProgress?: (percent: number, msg: string) => void,
  masterSize = 512,
): Promise<Blob> {
  const valid = icons.filter(isExportable);
  if (valid.length === 0) throw new Error('Tidak ada ikon yang siap diekspor. / No icons ready to export.');
  masterSize = clampSize(masterSize);

  const zip = new JSZip();
  const names = buildDrawableNames(valid.map((i) => i.appName));
  const entries: AppFilterEntry[] = [];
  const unmapped: string[] = [];
  const failed: string[] = [];
  const drawables: string[] = [];

  const totalSteps = valid.length * (DENSITIES.length + 1);
  let step = 0;
  const tick = (msg: string) => onProgress?.(Math.min(97, Math.round((++step / totalSteps) * 97)), msg);

  for (let idx = 0; idx < valid.length; idx++) {
    const icon = valid[idx];
    const name = names[idx];

    try {
      zip.file(`res/drawable-nodpi/${name}.png`, await renderPng(icon, masterSize, shape));
      tick(`${icon.appName} (${masterSize}px)`);
      for (const d of DENSITIES) {
        zip.file(`${d.folder}/${name}.png`, await renderPng(icon, d.size, shape));
        tick(`${icon.appName} (${d.size}px)`);
      }
      if (icon.svg) zip.file(`svg/${name}.svg`, sanitizeSvg(icon.svg));
    } catch (err) {
      console.error(`Failed to render ${icon.appName}:`, err);
      failed.push(icon.appName);
      continue;
    }

    drawables.push(name);
    const candidates = getComponentCandidates(icon.appName);
    if (candidates.length === 0) unmapped.push(icon.appName);
    for (const c of candidates) {
      entries.push({ drawable: name, appName: icon.appName, component: `${c.packageName}/${c.component}` });
    }
  }

  if (drawables.length === 0) throw new Error('Semua ikon gagal dirender. / Every icon failed to render.');

  const appFilter = buildAppFilterXml(entries, styleDNA.styleName);
  zip.file('assets/appfilter.xml', appFilter);
  zip.file('res/xml/appfilter.xml', appFilter);
  zip.file('assets/drawable.xml', buildDrawableXml(drawables));
  zip.file('res/xml/drawable.xml', buildDrawableXml(drawables));
  zip.file('style_dna.json', JSON.stringify(styleDNA, null, 2));
  zip.file('README_CARA_PAKAI_ANDROID.txt', buildReadme(styleDNA.styleName, shape, masterSize, drawables.length, unmapped, failed));

  onProgress?.(98, 'Membuat berkas ZIP / Building ZIP...');
  return zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 } });
}

